<?php
namespace Itb\Mcp;

/**
 * Сборка реестра инструментов под конкретный токен.
 *
 * ⚠️ Пока здесь один инструмент — `site_info`. Он нужен не для красоты: пока
 * цепочка «клиент → точка входа → Битрикс → ответ» не проверена на чём-то
 * заведомо простом, отлаживать поверх неё поиск по каталогу — значит искать
 * ошибку сразу в двух местах.
 *
 * Инструменты чтения каталога появятся здесь же, но их состав будет собираться
 * из настройки сайта: id инфоблоков и коды свойств у каждого сайта свои.
 */
class Tools
{
	/** @param string[]|null $allow null — всё разрешённое настройкой; список — только эти. */
	public static function build(?array $allow = null): Registry
	{
		$reg = new Registry();

		foreach (self::all() as $tool) {
			if ($allow !== null && !in_array($tool->name, $allow, true)) { continue; }
			$reg->add($tool);
		}

		$reg->setInstructions(
			"Это сайт на 1С-Битрикс. Сервер работает ТОЛЬКО НА ЧТЕНИЕ: изменить или удалить"
			. " что-либо через него нельзя.\n"
			. "Данные боевые — это работающий магазин, а не тестовый стенд.\n"
			. "Идентификаторы инфоблоков и коды свойств у каждого сайта свои: начните с"
			. " site_info, чтобы узнать, что доступно, и не подставляйте id по памяти."
		);

		return $reg;
	}

	/** @return Tool[] */
	private static function all(): array
	{
		return [
			new Tool(
				'site_info',
				'Сведения о сайте',
				'Название сайта, версия 1С-Битрикс, список подключённых модулей и перечень'
				. ' инфоблоков, открытых настройкой этого MCP-сервера. Зовите первым:'
				. ' остальные инструменты работают с идентификаторами, которые видны отсюда.',
				['type' => 'object', 'properties' => new \stdClass()],
				[self::class, 'siteInfo']
			),
		];
	}

	public static function siteInfo(array $args): array
	{
		$mods = [];
		foreach (['iblock', 'catalog', 'sale', 'highloadblock'] as $m) {
			$mods[$m] = \Bitrix\Main\Loader::includeModule($m);
		}

		return [
			'bitrix_version' => defined('SM_VERSION') ? SM_VERSION : 'неизвестна',
			'php_version'    => PHP_VERSION,
			'server_time'    => date('c'),
			'modules'        => $mods,
			// ⚠️ Пустой список означает «настройка ещё не заполнена», а не «на сайте
			// нет инфоблоков». Так и написано, иначе модель решит, что сайт пуст.
			'exposed_iblocks' => [],
			'note' => 'Белый список инфоблоков ещё не настроен — раздел настроек модуля'
				. ' в админке. Пока доступен только этот инструмент.',
		];
	}
}
