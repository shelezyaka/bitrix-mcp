<?php
namespace Itb\Mcp;

/**
 * Токен → реестр инструментов, доступных ИМЕННО ЭТОМУ токену.
 *
 * ⚠️⚠️ Возвращается не «да/нет», а реестр. Токен, которому инструмент не
 * разрешён, попросту его не видит в `tools/list` и не может позвать: запрет
 * держится на составе реестра, а не на одной проверке где-то в глубине вызова.
 *
 * ⚠️ Токен хранится ХЕШЕМ. Утечка настроек не должна давать доступ к сайту, а
 * показать значение обратно нельзя ни нам, ни владельцу: потерял — выпусти новый.
 * Хеш быстрый (sha256), и это осознанно: токен — 32 случайных байта, перебирать
 * там нечего, в отличие от пароля, который придумал человек.
 *
 * ⚠️ Сравнение только `hash_equals`. Обычное `===` на строках отвечает тем
 * быстрее, чем раньше разошлись байты, и по времени ответа токен подбирается
 * посимвольно.
 */
class Auth
{
	/**
	 * ⚠️ Пока — один токен в настройках модуля. Следующим шагом это станет
	 * таблицей: несколько токенов, у каждого свой белый список инструментов, срок
	 * и отзыв. Разбор и сверка от этого не изменятся — меняется только `lookup()`.
	 */
	private static function lookup(string $token): ?array
	{
		$stored = (string)\Bitrix\Main\Config\Option::get('itb.mcp', 'token_hash', '');
		if ($stored === '' || $token === '') { return null; }
		if (!hash_equals($stored, hash('sha256', $token))) { return null; }

		return ['title' => 'основной', 'tools' => null];   // null = все, что разрешает настройка
	}

	public static function registryFor(string $token): Registry
	{
		$row = self::lookup($token);
		if ($row === null) { throw new AuthError('токен не принят'); }

		return Tools::build($row['tools']);
	}
}
